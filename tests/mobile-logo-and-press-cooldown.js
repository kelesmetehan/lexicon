'use strict';
const fs=require('fs'),assert=require('assert');
const html=fs.readFileSync('outputs/lexicon-fixed.html','utf8');
const league=fs.readFileSync('outputs/league-v2.js','utf8');
const board=fs.readFileSync('outputs/board-confidence-reputation.js','utf8');
assert(league.includes('ll-team-logo-wrap'), 'runtime logo wrapper missing');
assert(league.includes('referrerpolicy="no-referrer"'), 'mobile-safe logo request policy missing');
assert(league.includes('ll-team-logo-fallback ${variant}'), 'text shield fallback missing');
assert(html.includes('.ll-team-logo-wrap'), 'logo wrapper CSS missing');
assert(html.includes('.ll-team-logo.is-failed'), 'failed logo CSS missing');
assert(html.includes('function llTeamLogo(teamOrName,variant=\'\')'), 'inline logo fallback missing');
assert(board.includes('PRESS_MAX_OFFERS_PER_SEASON=4'), 'seasonal press cap missing');
assert(board.includes('PRESS_MIN_OFFICIAL_MATCH_GAP=3'), 'press cooldown missing');
assert(board.includes('press.offers<PRESS_MAX_OFFERS_PER_SEASON'), 'press cap not wired to eligibility');
assert(board.includes('press.offers++;press.lastOfferMatch='), 'press offer state is not persisted');
const eligible=(matches,lastOffer,offers)=>offers<4&&matches-lastOffer>=3;
assert.equal(eligible(12,9,1),true,'third completed official-match gap must allow a new offer');
assert.equal(eligible(11,9,1),false,'consecutive offer must be blocked');
assert.equal(eligible(20,0,4),false,'season cap must block a fifth offer');
